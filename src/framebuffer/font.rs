const fn font_table() -> [[u8; 5]; 128] {
    let mut table = [[0u8; 5]; 128];
    let mut byte = 0;
    while byte < table.len() {
        table[byte] = glyph_data(byte as u8);
        byte += 1;
    }
    table
}

// Keep the lookup data in HP SRAM. The P4 ECO2 flash-cache boot path uses two
// XIP mappings, whereas the console needs this table during its first render.
#[used]
#[unsafe(link_section = ".data.font")]
static FONT: [[u8; 5]; 128] = font_table();

pub fn glyph(byte: u8) -> [u8; 5] {
    FONT[byte as usize]
}
